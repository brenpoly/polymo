/* ---------------------------------------------------------------------------
 * The rest of Material 3's colour roles.
 *
 * PLACEHOLDER, AND STRUCTURAL RATHER THAN CHOSEN. Only 12 of M3's 36 roles were
 * mapped, so the other 24 fell back to Material's baseline palette — which meant
 * every Card, ModalBottomSheet, dialog, OutlinedTextField border, divider and
 * scrim in this app was rendering in stock Material colours rather than these.
 * That is very likely why components here kept hardcoding colours: the defaults
 * looked wrong, so each one was overridden by hand.
 *
 * Generated by holding hue and chroma in LCh and sweeping L*, which approximates
 * how Material derives a tonal palette (HCT "tone" is CIELAB L*), with chroma
