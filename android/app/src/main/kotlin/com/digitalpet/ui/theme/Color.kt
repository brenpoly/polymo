/**
 * Gold that can be READ, for the light scheme only.
 *
 * `PetGold` `#F5A623` is a **fill** colour. On the light creams it measures
 * about **1.9:1** against a 4.5:1 requirement, so every gold label and every
 * gold icon on a light surface has been failing contrast since the light theme
 * shipped — a `TextButton`, an `OutlinedButton`, the send and microphone icons,
 * the focused field border. The mocks draw it as it renders rather than
 * darkening it quietly, which is how it came to be measured at all.
 *
 * **This value is the design system's own hover gold**, not one invented here,
 * and it clears AA on all three light surfaces: 5.1:1 on `background`, 5.6:1 on
 * `surface`, 4.8:1 on `surfaceVariant`.
 *
 * The alternative was darkening light `primary` itself. That was rejected
 * because `primary` is the identity: your message bubbles, the meters, the
 * usage-bar fill and the FAB are all gold *fills* with dark text on them, and
 * they neither need the change nor survive it — `onPrimary` would have to flip
 * to white and the warm theme would stop being warm. Fills keep the bright
 * gold; only foregrounds take this.
 */
