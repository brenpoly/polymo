#!/usr/bin/env python3
"""
Generate every surface that draws the pet's face from design-system/faces/*.json.

    tools/gen-faces.py            regenerate
    tools/gen-faces.py --check    exit 1 if anything would change (CI / pre-commit)

The pet's face is drawn FOUR times in four languages that cannot share code —
LVGL in C, Compose in Kotlin, a RemoteViews drawable in XML, and React in the
design project's click-through prototype. Before this, all of them were
hand-maintained and `PetFaceTest` existed purely to fail when they drifted. They
are generated now, so drift is not a thing that can happen rather than a thing
that gets caught.

**The fourth renderer is why this docstring says four.** `components/pet/faceSets.jsx`
was generated once by an earlier version of this script, then dropped out of it,
and spent a schema change sitting in the design project claiming in its own
header to be generated. It drew three sets with filled-lozenge mouths while the
device drew four with stroked arcs — i.e. it became the thing generation exists
to prevent, wearing the label that says it cannot be. **A file that says
GENERATED and is not is worse than a hand-maintained one**, because the header
tells every reader not to check it.

WHY THE JSON IS THE SOURCE, and not apply_mood(): DESIGN.md §7.2 — the design
system outranks, and a face is appearance. See design-system/faces/README.md for
the one exception that still belongs to the code.

Output is deterministic: running twice with no input change produces no diff.
That is what makes --check meaningful.
"""

