    for turns in used:
        for side, tag in ((0, "L"), (1, "R")):
            pts = spiral_unit(turns, side)
            rows = []
            for i in range(0, len(pts), 6):
                rows.append("        " + " ".join(
                    f"{x}, {y}," for x, y in pts[i:i + 6]))
            out += [f"    private val T{turns}_{tag} = intArrayOf(", *rows, "    )", ""]
    out += [
        "    /** The unit spiral of [turns] turns for [side] (0 is the left eye),",
        "     *  or null when no set winds that many — which is what a face with",
        "     *  ordinary eyes asks for, with turns of 0. */",
        "    fun points(turns: Int, side: Int): IntArray? = when (turns) {",
    ]
    for turns in used:
        out.append(f"        {turns} -> if (side == 0) T{turns}_L else T{turns}_R")
    out += [
        "        else -> null",
        "    }",
        "}",
        "",
    ]
    return out


