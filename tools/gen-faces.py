def gen_drawable(s, slot):
    """One VectorDrawable: the panel, two eyes, and the mouth if there is one.

    **This was a layer-list and could not stay one.** A layer-list places
    children by inset from an edge and draws only rectangles and ovals, so it
    can express a capsule mouth and nothing curved at all. A VectorDrawable
    draws paths, which covers both — the same rounded shapes as before, plus the
    arcs. minSdk is 31, well past the versions where a VectorDrawable in a
    RemoteViews would crash.

    Everything is drawn in a 48x48 viewport scaled from the device's 448-wide
    screen, so the badge is the same face at a different size rather than a
    second drawing of it.
    """
    g = s["faces"][slot]
    m = mouth(s, slot)
    k = NOTIF_PX / SCREEN_W          # device px -> viewport units
    c = s["colors"]
    mid = NOTIF_PX / 2
    lay = s["layout"]

    def rounded_rect_path(cx, cy, w, h, r):
        """A rounded rectangle as a path. r is clamped to half the short side,
        so a fully-rounded capsule and a square-cornered bar are the same code."""
        r = max(0.0, min(r, w / 2, h / 2))
        x0, y0, x1, y1 = cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2
        if r <= 0.01:
            return f"M{x0:.2f},{y0:.2f} H{x1:.2f} V{y1:.2f} H{x0:.2f} Z"
        return (f"M{x0 + r:.2f},{y0:.2f} H{x1 - r:.2f} "
                f"A{r:.2f},{r:.2f} 0 0 1 {x1:.2f},{y0 + r:.2f} "
                f"V{y1 - r:.2f} A{r:.2f},{r:.2f} 0 0 1 {x1 - r:.2f},{y1:.2f} "
                f"H{x0 + r:.2f} A{r:.2f},{r:.2f} 0 0 1 {x0:.2f},{y1 - r:.2f} "
                f"V{y0 + r:.2f} A{r:.2f},{r:.2f} 0 0 1 {x0 + r:.2f},{y0:.2f} Z")

    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {BANNER} -->",
        "<!--",
        f"    {s['name']} — the {slot} face at notification size.",
        "",
        "    Colours are literals because a notification is drawn by the system",
        "    UI in its own process and cannot read MaterialTheme. The panel is a",
        "    picture of hardware, so it does not follow the phone's scheme.",
        "-->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{NOTIF_PX}dp"',
        f'    android:height="{NOTIF_PX}dp"',
        f'    android:viewportWidth="{NOTIF_PX}"',
        f'    android:viewportHeight="{NOTIF_PX}">',
        "",
        "    <!-- The panel: a circular badge of unlit AMOLED. -->",
        "    <path",
        f'        android:fillColor="{c["panel"]}"',
        f'        android:pathData="M{mid},0 A{mid},{mid} 0 1 1 {mid},{NOTIF_PX} '
        f'A{mid},{mid} 0 1 1 {mid},0 Z" />',
    ]

    eye_r = lay["eyeRadius"]
    e = eyes(s, slot)
    sp = spiral(s, slot)
    ex = lay["eyeOffsetX"] * k
    ey = (lay["eyeOffsetY"] + e["gy"]) * k
    gx = e["gx"] * k
    for side, (sign, w, h) in enumerate(((-1, e["lw"], e["lh"]),
                                         (1, e["rw"], e["rh"]))):
        ew, eh = w * k, h * k
        ea = eye_arc(s, slot, side)
        cx = mid + sign * ex + gx
        if sp is not None:
            # A SPIRAL, AND IT IS STILL HERE. The badge cannot animate, so the
            # spin — which is most of what says "dizzy" on the device — is gone
            # and the shape has to carry the state on its own. It does: a spiral
            # is not a thing any other face wears, at any size.
            side_g = sp["sides"][side]
            # THE BADGE CAPS THE STROKE, where the mouth below FLOORS it, and
            # the asymmetry is the point. A hairline smile vanishes at 48dp, so
            # it gets thicker; a spiral shrunk to 8dp has ~2dp between its turns
            # and the same floor would weld them into a disc — which is a blank
            # stare, the one thing this face must not turn into. So it is
            # thinned to just under half the gap instead.
            gap = (side_g["r"] * k) / sp["turns"]
            stroke = min(max(0.9, side_g["thick"] * k), gap * 0.55)
            lines += [
                "",
                "    <path",
                f'        android:strokeColor="{c["eye"]}"',
                f'        android:strokeWidth="{stroke:.2f}"',
                '        android:strokeLineCap="round"',
                '        android:strokeLineJoin="round"',
                f'        android:pathData="'
                f'{spiral_path(side_g["pts"], side_g["r"], cx, mid + ey, k)}" />',
            ]
            continue
        if ea["kind"] == "arc":
            R = ea["r"] * k
            cy = mid + ey + ea["dy"] * k
            half_w = ew / 2
            ddy = math.sqrt(max(0.0, R * R - half_w * half_w))
            y = cy + ddy if ea["bulge"] > 0 else cy - ddy
            sweep = ea["sweep"]
            stroke = max(1.4, eh)
            lines += [
                "",
                "    <path",
                f'        android:strokeColor="{c["eye"]}"',
                f'        android:strokeWidth="{stroke:.2f}"',
                '        android:strokeLineCap="round"',
                f'        android:pathData="M{cx - half_w:.2f},{y:.2f} '
                f'A{R:.2f},{R:.2f} 0 0 {sweep} {cx + half_w:.2f},{y:.2f}" />',
            ]
            continue
        r = max(ew, eh) if eye_r == ROUND else eye_r * k
        lines += [
            "",
            "    <path",
            f'        android:fillColor="{c["eye"]}"',
            f'        android:pathData="'
            f'{rounded_rect_path(cx, mid + ey, ew, eh, r)}" />',
        ]

    if m["kind"] == "bar":
        w, t = m["w"] * k, m["thick"] * k
        lines += [
            "",
            "    <path",
            f'        android:fillColor="{c["mouth"]}"',
            f'        android:pathData="'
            f'{rounded_rect_path(mid, mid + lay["mouthOffsetY"] * k, w, t, t / 2 if m["round"] else 0)}" />',
        ]
    elif m["kind"] == "arc":
        # A stroked arc. The endpoints are the chord ends; the sweep is always
        # less than a semicircle (the schema refuses deeper), so large-arc is 0.
        R = m["r"] * k
        cy = mid + (lay["mouthOffsetY"] + m["dy"]) * k
        half_w = (m["w"] / 2) * k
        # y of the chord relative to the circle centre, from Pythagoras rather
        # than from the angles — one fewer trig round-trip to disagree about.
        dy = math.sqrt(max(0.0, R * R - half_w * half_w))
        y = cy + dy if m["bulge"] > 0 else cy - dy
        sweep = m["sweep"]
        # A hairline smile disappears at 48dp, so the stroke has a floor. It is
        # the badge that gets thicker, not the pet.
        stroke = max(1.6, m["thick"] * k)
        lines += [
            "",
            "    <path",
            f'        android:strokeColor="{c["mouth"]}"',
            f'        android:strokeWidth="{stroke:.2f}"',
            f'        android:strokeLineCap="{"round" if m["round"] else "butt"}"',
            f'        android:pathData="M{mid - half_w:.2f},{y:.2f} '
            f'A{R:.2f},{R:.2f} 0 0 {sweep} {mid + half_w:.2f},{y:.2f}" />',
        ]

    lines += ["", "</vector>", ""]
    return "\n".join(lines)


