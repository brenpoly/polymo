def mouth_label(m):
    """How to describe a mouth in a caption: a bar states its box, an arc states
    its curve. A designer reading the card should see the number they would
    change to make the smile deeper."""
    if m["kind"] == "none":
        return "<em>no mouth</em>"
    if m["kind"] == "bar":
        return f'<code>{m["w"]}&times;{m["thick"]}</code> flat'
    word = "smile" if m["bulge"] > 0 else "frown"
    return (f'<code>{m["w"]}</code> wide, <code>{abs(m["bulge"])}</code> {word}, '
            f'<code>{m["thick"]}</code> thick')


