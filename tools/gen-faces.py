def die(msg):
    sys.exit(f"gen-faces: {msg}")


def load_sets():
    sets = []
    for path in sorted(FACES_DIR.glob("*.json")):
        with open(path) as fh:
            try:
                data = json.load(fh)
            except json.JSONDecodeError as exc:
                die(f"{path.name}: {exc}")
        validate(data, path.name)
        sets.append(data)
    if not sets:
        die(f"no face sets found in {FACES_DIR}")
    ids = [s["id"] for s in sets]
    if len(set(ids)) != len(ids):
        die(f"duplicate set ids: {ids}")
    if "classic" not in ids:
        die("'classic' must exist — it is the fallback when NVS names an unknown set")
    # classic first: index 0 is the firmware's fallback.
    sets.sort(key=lambda s: (s["id"] != "classic", s["id"]))
    return sets


def validate(data, name):
    """Fail loudly here rather than producing C that will not compile."""
    for key in ("id", "name", "colors", "layout", "stageScale", "faces"):
        if key not in data:
            die(f"{name}: missing '{key}'")
    if not re.fullmatch(r"[a-z][a-z0-9_]{0,15}", data["id"]):
        die(f"{name}: id must be lowercase, <=16 chars, [a-z0-9_], got {data['id']!r}")
    for key in ("eye", "mouth", "panel", "text", "control"):
        val = data["colors"].get(key)
        if not isinstance(val, str) or not re.fullmatch(r"#[0-9A-Fa-f]{6}", val):
            die(f"{name}: colors.{key} must be #RRGGBB, got {val!r}")
    for key in ("eyeOffsetX", "eyeOffsetY", "mouthOffsetY", "eyeRadius"):
        if not isinstance(data["layout"].get(key), int):
            die(f"{name}: layout.{key} must be an integer")
    if data["layout"].get("mouthCap") not in ("round", "square"):
        die(f"{name}: layout.mouthCap must be 'round' or 'square'")
    for key in MOTION_KEYS:
        if not isinstance((data.get("motion") or {}).get(key), int):
            die(f"{name}: motion.{key} must be an integer — the set-level "
                "defaults are not optional, per-state overrides are")
    # A dead pet that breathes is the one motion bug worth failing the build on.
    if data["faces"]["dead"].get("motion", "unset") is not None:
        die(f"{name}: the dead face must have \"motion\": null — the absence of "
            "the blink and the breathe is what says it is not alive")
    for key in ("egg", "child", "teen", "adult"):
        pct = data["stageScale"].get(key)
        if not isinstance(pct, int) or not 1 <= pct <= 100:
            die(f"{name}: stageScale.{key} must be 1..100, got {pct!r}")
    missing = [s for s in SLOTS if s not in data["faces"]]
    if missing:
        die(f"{name}: missing faces: {', '.join(missing)}")
    extra = [s for s in data["faces"] if s not in SLOTS]
    if extra:
        die(f"{name}: unknown faces: {', '.join(extra)}")
    for slot, g in data["faces"].items():
        for key in ("eyeW", "eyeH", "mouthW", "mouthThickness", "mouthBulge"):
            if not isinstance(g.get(key), int):
                die(f"{name}: faces.{slot}.{key} must be an integer")
        m = g.get("motion", "unset")
        if m is not None and m != "unset":
            unknown = [k for k in m if k not in MOTION_KEYS]
            if unknown:
                die(f"{name}: faces.{slot}.motion has unknown keys: {unknown}")
        if g.get("mouthCap", "round") not in ("round", "square"):
            die(f"{name}: faces.{slot}.mouthCap must be 'round' or 'square'")
        if g["eyeW"] <= 0 or g["eyeH"] <= 0:
            die(f"{name}: faces.{slot} has no eyes; every face has eyes")
        for key in ("rightEyeW", "rightEyeH", "gazeX", "gazeY", "eyeBulge"):
            if key in g and not isinstance(g[key], int):
                die(f"{name}: faces.{slot}.{key} must be an integer")
        if g.get("rightEyeW", 1) <= 0 or g.get("rightEyeH", 1) <= 0:
            die(f"{name}: faces.{slot} has a right eye of zero size; to close an "
                "eye make it thin, not absent")
        # Far enough off centre and an eye leaves the panel, which reads as a
        # rendering fault rather than a glance.
        if abs(g.get("gazeX", 0)) > 40 or abs(g.get("gazeY", 0)) > 40:
            die(f"{name}: faces.{slot} gaze is more than 40px off centre; the "
                "eyes would leave the face")
        if g["mouthW"] > 0 and g["mouthThickness"] <= 0:
            die(f"{name}: faces.{slot} has a mouth of zero thickness")
        # A bulge deeper than half the chord would need a reflex arc, which
        # neither lv_arc nor a single SVG A-command draws the way you expect.
        if abs(g.get("eyeBulge", 0)) * 2 > g["eyeW"]:
            die(f"{name}: faces.{slot} eyeBulge {g.get('eyeBulge')} is more than "
                f"half its eye width {g['eyeW']}; keep it shallower than a "
                "semicircle")
        if g["mouthW"] > 0 and abs(g["mouthBulge"]) * 2 > g["mouthW"]:
            die(f"{name}: faces.{slot} bulge {g['mouthBulge']} is more than half "
                f"its chord {g['mouthW']}; keep it shallower than a semicircle")

        # --- spiral eyes ----------------------------------------------------
        shape = g.get("eyeShape", "rect")
        if shape not in ("rect", "spiral"):
            die(f"{name}: faces.{slot}.eyeShape must be 'rect' or 'spiral', "
                f"got {shape!r}")
        if shape != "spiral" and "spiralTurns" in g:
            die(f"{name}: faces.{slot} sets spiralTurns without "
                '"eyeShape": "spiral", so it draws nothing. A number that has '
                "no effect is worse than no number.")
        sm = motion(data, slot)
        if shape != "spiral" and sm and sm["spinMs"] > 0:
            die(f"{name}: faces.{slot} sets spinMs but its eyes are not a "
                "spiral. Nothing else on this face turns.")
        if shape == "spiral":
            if slot == "dead":
                die(f"{name}: the DEAD face may not be a spiral. It does not "
                    "move, and a spiral that has stopped is an ornament rather "
                    "than a symptom.")
            if g.get("eyeBulge", 0):
                die(f"{name}: faces.{slot} is both a spiral and an arc. An eye "
                    "is one shape; pick which.")
            turns = g.get("spiralTurns")
            if not isinstance(turns, int) or not 2 <= turns <= 4:
                die(f"{name}: faces.{slot}.spiralTurns must be an integer 2..4, "
                    f"got {turns!r}. One turn is a circle; five is a smudge at "
                    "48dp.")
            if not sm or sm["spinMs"] <= 0:
                die(f"{name}: faces.{slot} has spiral eyes that do not turn — "
                    'set motion.spinMs. **A still spiral is the whole reason '
                    "this shape was chosen and then wasted**: it is the "
                    "rotation the eye reads as dizzy, and a stopped one is a "
                    "pattern the pet happens to be wearing.")
            for label, w, h in (("left", g["eyeW"], g["eyeH"]),
                                ("right", g.get("rightEyeW", g["eyeW"]),
                                 g.get("rightEyeH", g["eyeH"]))):
                # The gap between consecutive turns. Below the stroke width the
                # turns touch and the spiral fills in as a disc — which is a
                # blank stare, and the one outcome this shape cannot afford.
                gap = (w / 2.0) / turns
                if gap < h * 1.5:
                    die(f"{name}: faces.{slot}'s {label} spiral fills in — "
                        f"{turns} turns across a radius of {w / 2:.0f}px leaves "
                        f"{gap:.1f}px between them and the stroke is {h}px.\n"
                        f"           Needs {h * 1.5:.1f}px of gap: fewer turns, "
                        "a wider eye, or a thinner stroke.")

    # A face may SUGGEST a voice, but only one that exists — a dangling id
    # would silently fall back to the default and look like the pairing simply
    # not working.
    persona = data.get("persona")
    if persona is not None:
        available = {p.stem for p in (ROOT / "design-system" / "personas").glob("*.json")}
        if persona not in available:
            die(f"{name}: persona names '{persona}', which is not in "
                f"design-system/personas/ ({', '.join(sorted(available)) or 'empty'})")

    semantics(data, name)
    check_contrast(data, name)
    check_arcs(data, name)


def _rel_luminance(hexstr):
    """WCAG relative luminance. The same arithmetic ContrastTest does for the
    app's colour schemes, applied to the pet's own palette."""
    def chan(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    v = int(hexstr[1:], 16)
    r, g, b = (v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF
    return 0.2126 * chan(r) + 0.7152 * chan(g) + 0.0722 * chan(b)


def contrast(a, b):
    la, lb = _rel_luminance(a), _rel_luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def check_contrast(data, name):
    """**The face has to be visible on its own panel.**

    Every set until now was light on black, where this could not go wrong. The
    first set to invert the palette is the first that could produce a pet nobody
    can read — and "is this legible" is arithmetic, so it does not need eyes.

    WCAG's 3:1 for non-text graphics covers the eyes and mouth; the spoken line
    is text and takes 4.5:1. Measured rather than eyeballed, for the same reason
    the app's schemes are: a ratio that looks fine on a bright monitor can be
    unreadable on a small panel across a room, which is exactly the distance the
    sad face has to work at.
    """
    c = data["colors"]
    # The talk button is an affordance, not a signal. It has to be findable and
    # must NOT compete with the face — a dark button on a pale panel reads as a
    # hole punched in the pet, which is exactly what a high ratio here produces.
    ctrl = contrast(c["control"], c["panel"])
    if ctrl < 1.1:
        die(f"{name}: the talk button vanishes into the panel — "
            f'{c["control"]} on {c["panel"]} is {ctrl:.2f}:1, needs 1.1:1.')
    if ctrl > 4.5:
        die(f"{name}: the talk button shouts louder than the pet — "
            f'{c["control"]} on {c["panel"]} is {ctrl:.2f}:1, keep it under '
            "4.5:1. It is a control, not an expression.")

    for key, floor, what in (("eye", 3.0, "eyes"),
                             ("mouth", 3.0, "mouth"),
                             ("text", 4.5, "spoken line")):
        ratio = contrast(c[key], c["panel"])
        if ratio < floor:
            die(f"{name}: the {what} are not legible on this panel — "
                f"{c[key]} on {c['panel']} is {ratio:.2f}:1, needs {floor}:1.\n"
                f"           WCAG {floor}:1 ({'text' if floor > 3 else 'non-text'}). "
                "The pet has to be readable across a room.")


def _svg_arc_midpoint(x1, y1, x2, y2, r, large, sweep):
    """Where an SVG/VectorDrawable arc ACTUALLY goes, by the spec's own
    endpoint-to-centre conversion (SVG 1.1 F.6.5), for a circle.

    Written out rather than reasoned about because reasoning about it is what
    produced the bug: `sweep = 1 if bulge > 0` reads right, and is inverted.
    """
    dx2, dy2 = (x1 - x2) / 2.0, (y1 - y2) / 2.0
    d = dx2 * dx2 + dy2 * dy2
    if d == 0:
        return (x1, y1)
    r = max(r, math.sqrt(d))                     # the spec's radius correction
    num = r * r - d
    factor = math.sqrt(max(0.0, num / d))
    if large == sweep:
        factor = -factor
    cx = factor * dy2 + (x1 + x2) / 2.0
    cy = -factor * dx2 + (y1 + y2) / 2.0
    t1 = math.atan2(y1 - cy, x1 - cx)
    t2 = math.atan2(y2 - cy, x2 - cx)
    dt = t2 - t1
    if sweep and dt < 0:
        dt += 2 * math.pi
    elif not sweep and dt > 0:
        dt -= 2 * math.pi
    mid = t1 + dt / 2.0
    return (cx + r * math.cos(mid), cy + r * math.sin(mid))


def check_arcs(data, name):
    """**The two representations of an arc must agree about which way it bends.**

    Every arc is emitted twice in different languages: as `start`/`end` angles
    plus a centre offset (the firmware's `lv_arc`, Compose's `drawArc`), and as
    an SVG path with a sweep flag (the notification's VectorDrawable, the
    design-system cards, the prototype). They are independent descriptions of
    the same curve, so they can disagree — and they did, for every curved face
    on every set, from the day arcs were introduced until 2026-08-11.

    The pet and the app take the angles and were right. The notification, the
    cards and the prototype take the path and drew every smile as a frown. The
    only surface anyone had looked at was one of the two correct ones.

    **This is the check that would have caught it, and its strength is that the
    two sides are genuinely independent** — one is the generator's angle output,
    the other is the SVG spec's own centre-parameterisation run over the exact
    path string that ships. `FaceSyncTest` could not have found it: it compares
    the Kotlin against the JSON, and both were correct.
    """
    for slot in SLOTS:
        arcs = [("mouth", mouth(data, slot))]
        arcs += [(f"eye{i}", eye_arc(data, slot, i)) for i in (0, 1)]
        for what, a in arcs:
            if a["kind"] != "arc":
                continue
            R, hw = a["r"], a["w"] / 2.0
            off = math.sqrt(max(0.0, R * R - hw * hw))
            # The chord, exactly as every path emitter places it.
            y = a["dy"] + off if a["bulge"] > 0 else a["dy"] - off
            mx, my = _svg_arc_midpoint(-hw, y, hw, y, R, 0, a["sweep"])
            path_down = my > y
            # ...and the angle form, as the C and the Kotlin receive it.
            midang = math.radians((a["start"] + a["end"]) / 2.0)
            angle_down = a["dy"] + R * math.sin(midang) > y
            if path_down != angle_down:
                die(f"{name}: faces.{slot} {what} bends one way as angles and the "
                    f"other as a path.\n"
                    f"           start/end {a['start']}..{a['end']} with centre "
                    f"dy {a['dy']} curves {'down' if angle_down else 'up'};\n"
                    f"           the SVG sweep flag {a['sweep']} curves "
                    f"{'down' if path_down else 'up'}.\n"
                    f"           The pet would smile and the notification frown. "
                    f"See arc_of().")
            # And the sign of the bulge is what both are supposed to mean.
            wants_down = a["bulge"] > 0
            if angle_down != wants_down:
                die(f"{name}: faces.{slot} {what} has bulge {a['bulge']} but bends "
                    f"{'down' if angle_down else 'up'}. Positive is DOWN.")


def semantics(data, name):
    """**What each state has to MEAN**, whatever a set makes it look like.

    A set may choose any colours and any geometry it likes. It may not lose the
    meaning: these states drive whether somebody feeds a pet, and a "happy" face
    that does not read as happy is not a style choice, it is a broken signal.

    Before this, only two of these were checked and the rest were a set author's
    good intentions — which is why `classic` shipped with a HAPPY face whose
    mouth was a flat bar. Nothing was wrong with it structurally. It just did
    not smile.

    Circles are exempt from the curve rules: a mouth as thick as it is wide is
    an "o", not a line, and asking whether it curves up or down is meaningless.
    """
    f = data["faces"]

    def circle(slot):
        g = f[slot]
        return g["mouthW"] > 0 and g["mouthW"] == g["mouthThickness"]

    def bulge(slot):
        return f[slot]["mouthBulge"]

    def fail(rule, detail):
        die(f"{name}: {rule}\n           {detail}")

    # --- the mouth says how it feels --------------------------------------
    if not circle("happy") and bulge("happy") <= 0:
        fail("a HAPPY face must smile.",
             f"faces.happy.mouthBulge is {bulge('happy')}; make it positive, or "
             "make the mouth a circle if this set means something else by happy.")
    if not circle("sad") and bulge("sad") >= 0:
        fail("a SAD face must turn its mouth down.",
             f"faces.sad.mouthBulge is {bulge('sad')}; make it negative. This is "
             "the face that has to make somebody go and feed the thing.")
    if not circle("neutral") and bulge("neutral") != 0:
        fail("a NEUTRAL face must be level.",
             "faces.neutral is the baseline every other state is read against, "
             "so it curves neither way.")

    # --- dead is the one state that cannot be undone -----------------------
    if f["dead"]["mouthW"] != 0:
        fail("the DEAD face must have no mouth.", "That is the whole message.")

    # --- the eyes open and close in an order -------------------------------
    ladder = [("surprised", ">"), ("neutral", None), ("sleepy", "<"), ("asleep", "<=")]
    n = f["neutral"]["eyeH"]
    if f["surprised"]["eyeH"] <= n:
        fail("a SURPRISED face must open its eyes wider than resting.",
             f'faces.surprised.eyeH is {f["surprised"]["eyeH"]}, resting is {n}.')
    if f["sleepy"]["eyeH"] >= n:
        fail("a SLEEPY face must have narrower eyes than resting.",
             f'faces.sleepy.eyeH is {f["sleepy"]["eyeH"]}, resting is {n}.')
    if f["asleep"]["eyeH"] > f["sleepy"]["eyeH"]:
        fail("an ASLEEP face must not have wider eyes than a SLEEPY one.",
             "asleep is the overlay for a pet that has actually gone to sleep.")
    if f["sad"]["eyeH"] >= n:
        fail("a SAD face must have lidded eyes.",
             f'faces.sad.eyeH is {f["sad"]["eyeH"]}, resting is {n}.')

    # --- sick is not a variation on sad ------------------------------------
    sad, sick = f["sad"], f["sick"]
    if (sad["eyeW"], sad["eyeH"]) == (sick["eyeW"], sick["eyeH"]):
        fail("SAD and SICK must not be confusable across a room.",
             "They mean different things and demand different actions — feed me "
             "versus put the phone down — so give them different eyes.")
    if (sad["mouthW"], sad["mouthThickness"], sad["mouthBulge"]) == \
       (sick["mouthW"], sick["mouthThickness"], sick["mouthBulge"]):
        fail("SAD and SICK must not share a mouth, for the same reason.",
             "Different eyes alone is not enough at a glance.")

    # --- nothing that is alive holds still ---------------------------------
    if f["dead"].get("motion", "unset") is not None:
        fail('the DEAD face must have "motion": null.',
             "The absence of the blink and the breathe is what says it is not "
             "alive; a still shape on its own is just a shape.")
    for slot in SLOTS:
        if slot == "dead":
            continue
        m = motion(data, slot)
        if m is None or m["breatheMs"] <= 0:
            fail(f"the {slot.upper()} face must breathe.",
                 "A still living pet reads as broken hardware — DESIGN.md §6.")
        # ASLEEP is exempt from blinking, and the exemption is the point: a
        # sleeping pet breathes and does not blink, because its eyes are already
        # shut. Requiring a blink here rejected correct data the first time this
        # rule ran, which is the good outcome — the rule was wrong, not the set.
        if slot != "asleep" and m["blinkMs"] <= 0:
            fail(f"the {slot.upper()} face must blink.",
                 "Only ASLEEP may hold its eyes shut.")

    # --- illness is legible before you look at the mouth --------------------
    sickm, happym = motion(data, "sick"), motion(data, "happy")
    if sickm["breatheMs"] >= happym["breatheMs"]:
        fail("a SICK face must breathe FASTER than a happy one.",
             f'sick is {sickm["breatheMs"]}ms, happy is {happym["breatheMs"]}ms.')
    if (sickm["breatheTo"] - sickm["breatheFrom"]) >= \
       (happym["breatheTo"] - happym["breatheFrom"]):
        fail("a SICK face must breathe SHALLOWER than a happy one.",
             "Shallow and fast is what reads as ill from across a room.")


def eyes(data, slot):
    """The two eyes, which are no longer required to be the same eye.

    `rightEyeW` / `rightEyeH` override the right eye only — an asymmetric face
    reads as queasy or sceptical in a way two identical eyes cannot, and it is
    the cheapest asymmetry available because the objects already exist. It was
    a heavier lid when the sick face had lids; on spiral eyes the same two
    numbers make one spiral smaller and heavier than the other.

    `gazeX` / `gazeY` move BOTH eyes off centre. A sad pet that also looks down
    and away is markedly sadder than one staring straight ahead, and it costs two
    integers. Positive gazeY looks down, matching the screen's own y axis rather
    than inventing a second convention.
    """
    g = data["faces"][slot]
    return {
        "lw": g["eyeW"], "lh": g["eyeH"],
        "rw": g.get("rightEyeW", g["eyeW"]),
        "rh": g.get("rightEyeH", g["eyeH"]),
        "gx": g.get("gazeX", 0), "gy": g.get("gazeY", 0),
    }


MOTION_KEYS = ("blinkMs", "shutMs", "breatheMs", "breatheFrom", "breatheTo",
               "spinMs")


def motion(data, slot):
    """How this face MOVES, resolved against the set's default.

    **Idle motion is identity** — DESIGN.md §6, "a still pet reads as broken" —
    and until now every mood moved identically: one 5400 ms blink, one 1900 ms
    breathe, for a dying pet and a delighted one alike. Making it per state is
    the cheapest expressiveness available: it costs no objects, no pixels and no
    rotation, because it only changes the numbers an animation already uses.

    `"motion": null` on a state means it does not move at all. That is how the
    dead face is expressed now — the absence of the blink and the breathe is
    the whole message, and it belongs in the data rather than as a special case
    in three renderers.
    """
    base = dict(data.get("motion") or {})
    over = data["faces"][slot].get("motion", "unset")
    if over is None:
        return None
    if over != "unset":
        base.update(over)
    return {k: int(base.get(k, 0)) for k in MOTION_KEYS}


def rgb(hexstr):
    return int(hexstr[1:], 16)


def arc_of(w, thick, bulge, round_cap):
    """A stroke along an arc, from its chord and sagitta. **The only trig here.**

    From chord w and sagitta s:  R = (w²/4 + s²) / 2s,  half-angle = asin(w/2R).

    Positive bulge curves DOWN, negative curves UP, and zero is a straight bar —
    which for a mouth is the capsule every face used before curves existed, and
    for an eye is the filled lozenge it always was.

    Deriving it once and emitting concrete radii and angles is the whole point.
    Four renderers each doing this arithmetic would be four chances to get it
    subtly different, and the difference would be a pet that smiles slightly
    wrong in the notification.
    """
    out = {"w": w, "thick": thick, "bulge": bulge, "round": round_cap,
           "r": 0, "dy": 0, "start": 0, "end": 0}
    if w <= 0 or thick <= 0:
        out["kind"] = "none"
        return out
    if bulge == 0:
        out["kind"] = "bar"
        return out

    a = abs(bulge)
    R = (w * w / 4.0 + a * a) / (2.0 * a)
    half = math.degrees(math.asin(min(1.0, (w / 2.0) / R)))
    out["kind"] = "arc"
    out["r"] = int(round(R))
    # THE SVG SWEEP FLAG, DERIVED HERE AND NOWHERE ELSE.
    #
    # It was `1 if bulge > 0`, written out separately in each of the FIVE places
    # that needed it, and it is INVERTED — so every arc came out upside down on
    # every surface that takes a path rather than an angle. The pet smiled and
    # the notification frowned. Found on a phone, 2026-08-11, and a face is
    # generated precisely so that cannot happen.
    #
    # Why 0: the chord runs left to right and, for a downward bulge, the
    # circle's centre is ABOVE it. With large-arc-flag 0 the renderer takes the
    # short arc, and around a centre above the chord the short arc dips BELOW
    # the chord only when swept counter-clockwise on a y-down canvas — sweep 0.
    # Sweep 1 forces the other candidate centre and flips the curve.
    #
    # The C and the Kotlin were always right: they take `start`/`end` angles and
    # `dy`, which say where the arc IS rather than which way round to reach it.
    # That asymmetry is why this survived — the two surfaces anyone looks at
    # were correct.
    out["sweep"] = 0 if bulge > 0 else 1
    # 0° is 3 o'clock going clockwise with y down, so 90° is the bottom of the
    # circle. Curving DOWN is the bottom of a circle centred above the chord;
    # curving UP is the top of one centred below it.
    out["start"] = int(round((90 if bulge > 0 else 270) - half))
    out["end"] = int(round((90 if bulge > 0 else 270) + half))
    out["dy"] = int(round(-(R - a) if bulge > 0 else (R - a)))
    return out


def mouth(data, slot):
    """The mouth as every renderer needs it."""
    g = data["faces"][slot]
    cap = g.get("mouthCap", data["layout"]["mouthCap"]) == "round"
    return arc_of(g["mouthW"], g["mouthThickness"], g["mouthBulge"], cap)


def eye_arc(data, slot, side):
    """One eye. `eyeBulge` turns it from a filled lozenge into a stroke.

    **This is what draws the classic "^ ^".** The firmware's own comment for the
    happy face has always described squinted eyes that way; it simply had no
    vocabulary for a curve, so "squinted" came out as a flattened capsule.

    When an eye curves, its HEIGHT becomes the stroke thickness — the same
    relationship `mouthThickness` has to `mouthW`, so there is one concept here
    rather than two.
    """
    e = eyes(data, slot)
    g = data["faces"][slot]
    w, h = (e["lw"], e["lh"]) if side == 0 else (e["rw"], e["rh"])
    return arc_of(w, h, g.get("eyeBulge", 0), data["layout"]["eyeRadius"] == ROUND)


# --------------------------------------------------------------- spirals -----

# Points per turn. Chosen from the outer turn, which is the one that shows the
# faceting: at the largest radius any set uses (~40px) a turn is ~250px around,
# so 24 segments is a ~10px chord — smooth at arm's length and on a 48dp badge.
SPIRAL_STEPS_PER_TURN = 24
# The unit the canonical points are in: per-mille of the spiral's OUTER radius.
# Integers rather than floats because three of the five renderers take a table
# and a float table would be three roundings of the same number.
SPIRAL_UNIT = 1000


def spiral_unit(turns, side):
    """**The canonical spiral, and the only place its shape is decided.**

    An Archimedean spiral — radius proportional to angle, so the gap between
    turns is constant, which is what makes it read as a spiral rather than as a
    smear. Emitted in per-mille of the outer radius so ONE table serves every
    set: a renderer multiplies by the eye's own radius and nothing re-derives
    the curve.

    `side` 1 is the right eye, and it is the SAME spiral mirrored in x. That is
    the sick face's asymmetry: two spirals wound opposite ways read as woozy,
    where two identical ones read as a logo.

    **Both sides are emitted rather than one plus a "negate x" rule.** The rule
    would be a convention each of five renderers implements separately, which is
    exactly the shape of the bug that made every smile a frown until 2026-08-11
    — see arc_of(). A table cannot be mirrored the wrong way.
    """
    n = SPIRAL_STEPS_PER_TURN * turns + 1
    pts = []
    for k in range(n):
        t = k / (n - 1)                       # 0 at the centre, 1 at the rim
        ang = 2 * math.pi * turns * t
        r = SPIRAL_UNIT * t
        x, y = r * math.cos(ang), r * math.sin(ang)
        pts.append((int(round(-x if side else x)), int(round(y))))
    return pts


def spiral(data, slot):
    """The spiral eyes of one face, or None if this face has ordinary eyes.

    `eyeW` is the OUTER DIAMETER and `eyeH` the stroke — the same relationship a
    curved eye already has, where the height becomes the line weight. So a
    spiral needs no new size fields: it reinterprets the two the schema has.
    """
    g = data["faces"][slot]
    if g.get("eyeShape") != "spiral":
        return None
    e, turns = eyes(data, slot), g["spiralTurns"]
    m = motion(data, slot) or {}
    return {
        "turns": turns,
        "n": SPIRAL_STEPS_PER_TURN * turns + 1,
        "spin": m.get("spinMs", 0),
        "sides": [
            {"r": w / 2.0, "thick": h, "pts": spiral_unit(turns, side)}
            for side, (w, h) in enumerate(((e["lw"], e["lh"]), (e["rw"], e["rh"])))
        ],
    }


def spiral_turns(data, slot):
    """How many turns this face's eyes wind, or 0 for ordinary eyes. The C and
    the Kotlin tables both carry it as a plain number."""
    sp = spiral(data, slot)
    return sp["turns"] if sp else 0


def spiral_path(pts, radius, cx, cy, k=1.0):
    """The same points as an SVG polyline, scaled and placed.

    Shared by the notification drawable, both design-system cards and the
    prototype, so the four surfaces that take a path get one string from one
    table rather than four polylines.
    """
    out = []
    for i, (x, y) in enumerate(pts):
        px = cx + x * radius * k / SPIRAL_UNIT
        py = cy + y * radius * k / SPIRAL_UNIT
        out.append(f"{'M' if i == 0 else 'L'}{px:.2f},{py:.2f}")
    return " ".join(out)


