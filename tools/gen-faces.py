def _tag_class(part, cls):
    """Add a class to a part emitted by `_face_parts`.

    It cannot be wrapped instead, which is the obvious thing to try: the parts
    are absolutely positioned against the face box, and a wrapper carrying a
    `transform` becomes their containing block — so the eyes would resolve their
    `50%` against a zero-sized span and pile up in the corner.

    An eye is an `<i>` when it is a lozenge and an `<svg>` when it curves, so
    both are handled rather than assuming today's `classic`.
    """
    for tag in ("<i ", "<svg "):
        if part.startswith(tag):
            return part.replace(tag, f'{tag[:-1]} class="{cls}" ', 1)
    die(f"unexpected face part, cannot tag it: {part[:40]!r}")


def gen_motion_card(sets):
    """`guidelines/motion.html` — the motion card.

    **It was hand-written and asserted a single blink of 5400 ms**, "the
    firmware's own number, so the two surfaces agree". That was true when there
    was one number. Motion is per state and per set now, and the card was
    quietly describing a system with one clock.

    I nearly rewrote it by hand with a table of `classic`'s numbers typed into
    it, which is the same mistake with a longer half-life — so the table is
    generated and the prose is not. The prose is about the APP's motion policy,
    which is a decision rather than data.
    """
    canon = next(s for s in sets if s["id"] == "classic")
    rows = []
    for slot in SLOTS:
        mo = motion(canon, slot)
        if mo is None:
            rows.append(f'<tr><td>{slot}</td><td class="m">&mdash;</td>'
                        f'<td class="m">&mdash;</td><td class="m">&mdash;</td>'
                        f'<td class="m">&mdash;</td><td class="m">&mdash;</td></tr>')
            continue
        blink = f'{mo["blinkMs"]} ms' if mo["blinkMs"] > 0 else "&mdash;"
        shut = f'{mo["shutMs"]} ms' if mo["blinkMs"] > 0 else "&mdash;"
