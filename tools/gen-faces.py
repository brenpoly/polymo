# ---------------------------------------------------------------- C -----------

def gen_c_spirals(sets):
    """The unit spirals, one table per distinct turn count, plus the lookup.

    Per-mille of the eye's own outer radius, so all four sets share one curve
    and the device multiplies rather than deriving. The tables are `const`, so
    they live in flash: 49 points is 196 bytes, and only the sick face uses one.

    Each has a LEFT and a RIGHT table, and the right is the mirror. The pet
    could negate x itself in three lines — and that would put the mirroring
    convention in every renderer separately, which is precisely how the arc
    sweep flag came to be inverted on three surfaces at once. See arc_of().
    """
    used = sorted({sp["turns"] for s in sets for slot in SLOTS
                   if (sp := spiral(s, slot))})
    out = [
        "/* --- spiral eyes ------------------------------------------------------",
        " *",
        " * The face the pet wears when it is ill. Points are x,y pairs in",
        f" * PER-MILLE of the spiral's outer radius, so one table serves every set:",
        " * scale by eye_w/2 and place at the eye's centre. Nothing here derives a",
        " * curve — see arc_of() in tools/gen-faces.py for why that arithmetic",
        " * happens once for all the renderers rather than four times.",
        " */",
        f"#define PET_SPIRAL_STEPS_PER_TURN {SPIRAL_STEPS_PER_TURN}",
        f"#define PET_SPIRAL_UNIT {SPIRAL_UNIT}",
    ]
    if not used:
        out += [
            "#define PET_SPIRAL_MAX_POINTS 0",
            "",
            "typedef struct {",
            "    uint8_t turns;",
            "    uint16_t n;",
            "    const int16_t *left;   /* n pairs: x, y */",
            "    const int16_t *right;  /* the same spiral, mirrored */",
            "} pet_spiral_t;",
            "",
            "#define PET_SPIRAL_COUNT 0",
            "static const pet_spiral_t pet_spirals[1] = { { 0, 0, NULL, NULL } };",
            "",
        ]
    else:
        for turns in used:
            for side, tag in ((0, "l"), (1, "r")):
                pts = spiral_unit(turns, side)
                rows = []
                for i in range(0, len(pts), 6):
                    rows.append("    " + " ".join(
                        f"{x}, {y}," for x, y in pts[i:i + 6]))
                out += [
                    "",
                    f"static const int16_t pet_spiral_t{turns}_{tag}"
                    f"[{2 * len(pts)}] = {{",
                    *rows,
                    "};",
                ]
        biggest = max(SPIRAL_STEPS_PER_TURN * t + 1 for t in used)
        out += [
            "",
            f"#define PET_SPIRAL_MAX_POINTS {biggest}",
            "",
            "typedef struct {",
            "    uint8_t turns;",
            "    uint16_t n;",
            "    const int16_t *left;   /* n pairs: x, y */",
            "    const int16_t *right;  /* the same spiral, mirrored */",
            "} pet_spiral_t;",
            "",
            f"#define PET_SPIRAL_COUNT {len(used)}",
            "static const pet_spiral_t pet_spirals[PET_SPIRAL_COUNT] = {",
        ]
        for turns in used:
            n = SPIRAL_STEPS_PER_TURN * turns + 1
            out.append(f"    {{ {turns}, {n}, pet_spiral_t{turns}_l, "
                       f"pet_spiral_t{turns}_r }},")
        out += ["};", ""]
    out += [
        "/* The table for a face's turn count, or NULL if it has no spiral. A",
        " * face_geom with eye_spiral_turns of 0 is every face but the sick one. */",
        "static inline const pet_spiral_t *pet_spiral_of(int turns)",
        "{",
        "    for (int i = 0; i < PET_SPIRAL_COUNT; i++) {",
        "        if (pet_spirals[i].turns == turns) {",
        "            return &pet_spirals[i];",
        "        }",
        "    }",
        "    return NULL;",
        "}",
        "",
    ]
    return out


