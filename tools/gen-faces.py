def _shape_payload(a, radius):
    """One stroke — an eye or a mouth — as the prototype needs to draw it.

    **Resolved, not raw.** `arc_of` derives the radius, the sweep angles and the
    centre offset from a chord and a sagitta, and its own docstring says why
    that arithmetic is done once: four renderers each doing the trig would be
    four chances to get a smile subtly wrong. So the JSX gets the answers, the
    same way the C table and the Kotlin do — it never sees `mouthBulge`.
    """
    out = {"kind": a["kind"]}
    if a["kind"] == "none":
        return out
    out.update({"w": a["w"], "thick": a["thick"], "round": bool(a["round"])})
    if a["kind"] == "bar":
        out["radius"] = radius
    else:
        out.update({"r": a["r"], "dy": a["dy"],
                    "start": a["start"], "end": a["end"],
                    "sweep": a["sweep"]})
    return out


def gen_jsx(sets):
    """`components/pet/faceSets.jsx` — the data half of the design project's
    click-through prototype.

    **Data only.** `PetPanel.jsx` is hand-written and does the drawing, which is
    the same split the app has: `PetFaceSets.kt` is generated and the Compose
    panel that reads it is not. A generator that emitted the renderer too would
    be maintaining React, and it has no business doing that.

    Geometry is DEVICE PIXELS on the 448x368 landscape screen with the origin at
    the centre of the panel, so `cx`/`cy` are what you add to `50%`. The
    prototype scales by `width / 448` and nothing else.
    """
    payload = {}
    for s in sets:
        lay = s["layout"]
        eye_radius = 999 if lay["eyeRadius"] == ROUND else lay["eyeRadius"]
        faces = {}
        for slot in SLOTS:
            e = eyes(s, slot)
            sp = spiral(s, slot)
            eye_shapes = []
            for side, sign in ((0, -1), (1, 1)):
                if sp is not None:
                    g = sp["sides"][side]
                    shape = {"kind": "spiral", "thick": g["thick"],
                             "turns": sp["turns"], "spinMs": sp["spin"],
                             "d": spiral_path(g["pts"], g["r"], 0, 0),
                             "box": 2 * g["r"] + g["thick"]}
                else:
                    shape = _shape_payload(eye_arc(s, slot, side), eye_radius)
                shape["cx"] = sign * lay["eyeOffsetX"] + e["gx"]
                shape["cy"] = lay["eyeOffsetY"] + e["gy"]
                eye_shapes.append(shape)
            m = mouth(s, slot)
            mouth_shape = _shape_payload(
                m, (m["thick"] / 2 if m["round"] else 0) if m["kind"] == "bar" else 0)
            mouth_shape["cy"] = lay["mouthOffsetY"]
            faces[slot] = {
                "eyes": eye_shapes,
                "mouth": mouth_shape,
                "motion": motion(s, slot),
            }
        payload[s["id"]] = {
            "id": s["id"],
            "name": s["name"],
            "description": s.get("description", ""),
            "persona": s.get("persona"),
            "colors": s["colors"],
            "stageScale": s["stageScale"],
            "faces": faces,
        }

    def js(obj):
        return json.dumps(obj, indent=2, sort_keys=False)

    return f"""/* {BANNER}
   The design project's path for this file is components/pet/faceSets.jsx.

   DATA ONLY — PetPanel.jsx draws it, and is hand-written. Same split as the
   app: PetFaceSets.kt is generated, the Compose panel that reads it is not.

   Sizes are DEVICE PIXELS on the pet's {SCREEN_W}x{SCREEN_H} screen. That screen is
   LANDSCAPE: the panel is wired portrait and the firmware rotates it 270
   degrees (PET_ROTATION_DEG in pet-esp32.c), so landscape is what anyone ever
   sees. `cx` / `cy` are centres relative to the middle of the panel.

   Every stroke is pre-resolved. `kind` is one of:
     "none"  nothing to draw — the dead face has no mouth
     "bar"   a filled lozenge `w` x `thick`, corner radius `radius`
     "arc"   a stroke `thick` wide along a circle of radius `r`, whose centre
             sits `dy` from the shape's own centre, swept from `start` to `end`
             degrees (0 at 3 o'clock, clockwise, y down) with SVG sweep flag
             `sweep`. `round` is the line cap.
     "spiral" a stroke `thick` wide along the path `d`, inside a square of side
             `box` centred on the eye, TURNING once every `spinMs`. Only the
             sick face wears it. The spin is not decoration: a spiral that has
             stopped reads as a pattern rather than as a symptom, so a
             prototype that drew this still would be drawing a different face.
   The trig that produced `r` / `dy` / `start` / `end` lives in gen-faces.py and
   is done ONCE, for all four renderers — see arc_of(). A renderer that
   re-derived it would be a fourth chance to draw the smile slightly wrong.

   `motion` is null for a state that does not move, which is how `dead` says it
   is dead. Otherwise blinkMs 0 means "this state does not blink". */
export const PET_SCREEN = {{ width: {SCREEN_W}, height: {SCREEN_H} }};

export const FACE_SETS = {js(payload)};

/* The picker's order, and the order the wire uses. `classic` is index 0 because
   it is the firmware's fallback when NVS names a set it does not have. */
export const FACE_SET_IDS = {js([s["id"] for s in sets])};

/* All eight. `asleep` is a real state with its own geometry and motion, not a
   modifier applied to another one. */
export const FACE_STATES = {js(SLOTS)};

/* The five the PHONE may draw. `sleepy` and `surprised` are written by the
   phone, decay on the device and are never reported back, so the app cannot
   know when one is showing and does not guess — rule 2, never assert what we
   have not been told. `asleep` is the pet's own and travels no better. */
export const APP_DRAWN_STATES = {js(APP_FACES)};
"""


# ------------------------------------------------------------- driver --------

def write(path, content, check, changed):
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text() if path.exists() else None
    if old == content:
        return
    changed.append(path.relative_to(ROOT))
    if not check:
        path.write_text(content)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="report what would change and exit 1; write nothing")
    args = ap.parse_args()

    sets = load_sets()
    changed = []

    write(C_OUT, gen_c(sets), args.check, changed)
    write(KT_OUT, gen_kotlin(sets), args.check, changed)
    write(JSX_OUT, gen_jsx(sets), args.check, changed)
    write(BRAND_OUT, gen_brand_card(sets), args.check, changed)
    write(PALETTE_OUT, gen_palette_card(sets), args.check, changed)
    write(MOTION_OUT, gen_motion_card(sets), args.check, changed)
    write(VOICE_OUT, gen_voice_card(sets), args.check, changed)
    for s in sets:
        write(PREVIEW_DIR / f"{s['id']}.card.html", gen_preview(s), args.check, changed)
        for slot in SLOTS:
            name = f"pet_face_{s['id']}_{slot}.xml"
            write(DRAWABLE_DIR / name, gen_drawable(s, slot), args.check, changed)

    if args.check:
        if changed:
            print("gen-faces: OUT OF DATE — run tools/gen-faces.py")
            for p in changed:
                print(f"  {p}")
            return 1
        print(f"gen-faces: up to date ({len(sets)} sets)")
        return 0

    print(f"gen-faces: {len(sets)} sets -> "
          f"{len(changed)} file(s) written" if changed else
          f"gen-faces: {len(sets)} sets, already up to date")
    for p in changed:
        print(f"  {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
