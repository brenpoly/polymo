def _face_parts(s, slot):
    """One face as absolutely-positioned HTML, in DEVICE PIXELS.

    Shared by the per-set preview cards and the brand card, so a specimen
    anywhere in the design system is the same drawing from the same numbers.
    The caller supplies a `.screen` box and scales it; nothing here knows what
    size it will be shown at.
    """
    c, lay = s["colors"], s["layout"]
    eye_radius = "999px" if lay["eyeRadius"] == ROUND else f'{lay["eyeRadius"]}px'
    parts = []
    e = eyes(s, slot)
    sp = spiral(s, slot)
    for side, (sign, ew, eh) in enumerate(((-1, e["lw"], e["lh"]),
                                           (1, e["rw"], e["rh"]))):
        if sp is not None:
            # The spin is the state, so the card spins. A card that showed a
            # motionless spiral would be showing a different face from the one
            # the pet wears — the same class of quiet lie as a card whose smile
            # curves the other way, which this file also once shipped.
            g = sp["sides"][side]
            box = 2 * g["r"] + g["thick"]
            cx = sign * lay["eyeOffsetX"] + e["gx"]
            cy = lay["eyeOffsetY"] + e["gy"]
            parts.append(
                f'<svg width="{box:g}" height="{box:g}" '
                f'viewBox="{-box/2:g} {-box/2:g} {box:g} {box:g}" '
                f'style="position:absolute;display:block;'
                f'left:calc(50% + {cx - box/2:g}px);'
                f'top:calc(50% + {cy - box/2:g}px);overflow:visible;'
                f'animation:pet-spin {sp["spin"]}ms linear infinite">'
                f'<path d="{spiral_path(g["pts"], g["r"], 0, 0)}" '
                f'fill="none" stroke="{c["eye"]}" stroke-width="{g["thick"]}" '
                f'stroke-linecap="round" stroke-linejoin="round"/></svg>'
            )
            continue
        ea = eye_arc(s, slot, side)
        if ea["kind"] == "arc":
            R, hw = ea["r"], ew / 2
            ddy = math.sqrt(max(0.0, R * R - hw * hw))
            cy = lay["eyeOffsetY"] + e["gy"] + ea["dy"]
            yy = cy + ddy if ea["bulge"] > 0 else cy - ddy
            sw = ea["sweep"]
            box = 2 * R + eh
            cx = sign * lay["eyeOffsetX"] + e["gx"]
            parts.append(
                f'<svg width="{box:g}" height="{box:g}" '
                f'viewBox="{-box/2:g} {-box/2:g} {box:g} {box:g}" '
                f'style="position:absolute;display:block;'
                f'left:calc(50% + {cx - box/2:g}px);'
                f'top:calc(50% - {box/2:g}px);overflow:visible">'
                f'<path d="M{-hw:g},{yy:g} A{R:g},{R:g} 0 0 {sw} {hw:g},{yy:g}" '
                f'fill="none" stroke="{c["eye"]}" stroke-width="{eh}" '
                f'stroke-linecap="round"/></svg>'
            )
            continue
        parts.append(
            f'<i style="position:absolute;display:block;left:calc(50% + '
            f'{sign * lay["eyeOffsetX"] + e["gx"] - ew / 2:g}px);'
            f'top:calc(50% + {lay["eyeOffsetY"] + e["gy"] - eh / 2:g}px);'
            f'width:{ew}px;height:{eh}px;'
            f'background:{c["eye"]};border-radius:{eye_radius}"></i>'
        )
    m = mouth(s, slot)
    if m["kind"] == "bar":
        mr = f'{m["thick"] / 2:g}px' if m["round"] else "0"
        parts.append(
            f'<i style="position:absolute;display:block;'
            f'left:calc(50% - {m["w"] / 2:g}px);'
            f'top:calc(50% + {lay["mouthOffsetY"] - m["thick"] / 2:g}px);'
            f'width:{m["w"]}px;height:{m["thick"]}px;'
            f'background:{c["mouth"]};border-radius:{mr}"></i>'
        )
    elif m["kind"] == "arc":
        # An inline SVG so the card curves exactly as the device does,
        # from the same emitted radius rather than a CSS approximation.
        R, hw = m["r"], m["w"] / 2
        dy = math.sqrt(max(0.0, R * R - hw * hw))
        cy = lay["mouthOffsetY"] + m["dy"]
        y = cy + dy if m["bulge"] > 0 else cy - dy
        sweep = m["sweep"]
        box = 2 * R + m["thick"]
        parts.append(
            f'<svg width="{box:g}" height="{box:g}" '
            f'viewBox="{-box/2:g} {-box/2:g} {box:g} {box:g}" '
            f'style="position:absolute;display:block;'
            f'left:calc(50% - {box/2:g}px);'
            f'top:calc(50% - {box/2:g}px);overflow:visible">'
            f'<path d="M{-hw:g},{y:g} A{R:g},{R:g} 0 0 {sweep} {hw:g},{y:g}" '
            f'fill="none" stroke="{c["mouth"]}" stroke-width="{m["thick"]}" '
            f'stroke-linecap="{"round" if m["round"] else "butt"}"/></svg>'
        )
    return parts


def eye_label(s, slot):
    """How to describe a face's eyes in a caption.

    A spiral's `eyeW` is a diameter and its `eyeH` a stroke, so printing them as
    a box — which is what every caption did — would describe a shape the card is
    visibly not drawing."""
    g, e = s["faces"][slot], eyes(s, slot)
    sp = spiral(s, slot)
    if sp is not None:
        return (f'<code>{sp["turns"]}</code>-turn spirals, '
                f'<code>{e["lw"]}</code> across, '
                f'<code>{sp["spin"]}</code> ms a turn')
    if g.get("eyeBulge", 0):
        return f'<code>{e["lw"]}</code> wide curved eyes'
    return f'<code>{e["lw"]}&times;{e["lh"]}</code> eyes'


